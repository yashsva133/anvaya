import type { AnswerLang } from "./languages";

export type ConversationKind =
  | "greeting"
  | "thanks"
  | "identity"
  | "goodbye"
  | "acknowledgement"
  | "capability";

/** Keep punctuation out of the small-talk matcher without touching words in any script. */
function normalise(text: string): string {
  return text
    .trim()
    .toLocaleLowerCase()
    .replace(/[!?.,;:()[\]{}'"“”‘’`]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Classify only short, unambiguous social turns. A message such as
 * "hello, why is my hemoglobin low?" deliberately falls through to the report
 * pipeline instead of losing the medical question after the greeting.
 */
export function detectConversation(text: string): ConversationKind | null {
  const q = normalise(text);
  if (!q || q.length > 80) return null;

  if (
    /^(?:hi|hello|hey|hiya|heya|namaste|good morning|good afternoon|good evening|नमस्ते|नमस्कार|सुप्रभात|शुभ संध्या|হ্যালো|নমস্কার|வணக்கம்|నమస్కారం|नमस्कार|નમસ્તે|ನಮಸ್ಕಾರ|നമസ്കാരം|ਸਤ ਸ੍ਰੀ ਅਕਾਲ|السلام علیکم|ସୁପ୍ରଭାତ|নমস্কাৰ|नमस्ते)(?: (?:there|anvaya))?$/.test(
      q
    )
  ) {
    return "greeting";
  }

  // Keep ordinary social conversation natural as well. These are deliberately
  // exact short turns; "how are you, and why is my Hb low?" must still reach
  // the report-aware path rather than losing the medical question.
  if (
    /^(?:how are you(?: doing)?|how is it going|what s up|nice to meet you|good to see you|आप कैसे हैं|आप कैसी हैं|कैसे हो|কেমন আছেন|நீங்கள் எப்படி இருக்கிறீர்கள்|ఎలా ఉన్నారు|तुम्ही कसे आहात|તમે કેમ છો|ನೀವು ಹೇಗಿದ್ದೀರಿ|സുഖമാണോ|ਤੁਸੀਂ ਕਿਵੇਂ ਹੋ|آپ کیسے ہیں|ଆପଣ କେମିତି ଅଛନ୍ତି|আপুনি কেনে আছে)$/.test(
      q
    )
  ) {
    return "greeting";
  }

  if (
    /^(?:help|help me|can you help|can you help me|please help|मदद|मदद करें|সাহায্য|உதவி|సహాయం|मदत करा|મદદ|ಸಹಾಯ|സഹായം|ਮਦਦ|مدد|ସାହାଯ୍ୟ|সহায়তা|सहायता)$/.test(
      q
    )
  ) {
    return "capability";
  }

  if (
    /^(?:thanks|thank you|thankyou|thx|many thanks|you're welcome|धन्यवाद|शुक्रिया|ধন্যবাদ|நன்றி|ధన్యవాదాలు|धन्यवाद|આભાર|ಧನ್ಯವಾದ|നന്ദി|ਧੰਨਵਾਦ|شکریہ|ଧନ୍ୟବାଦ|ধন্যবাদ)$/.test(
      q
    )
  ) {
    return "thanks";
  }

  if (
    /^(?:who are you|what are you|what can you do|how can you help|tell me about yourself|आप कौन हैं|तुम कौन हो|आप क्या कर सकते हैं|আপনি কে|நீங்கள் யார்|మీరు ఎవరు|तुम्ही कोण आहात|તમે કોણ છો|ನೀವು ಯಾರು|നിങ്ങൾ ആരാണ്|ਤੁਸੀਂ ਕੌਣ ਹੋ|آپ کون ہیں|ଆପଣ କିଏ|আপুনি কোন)$/.test(
      q
    )
  ) {
    return q.includes("what can") || q.includes("how can") || q.includes("क्या कर")
      ? "capability"
      : "identity";
  }

  if (
    /^(?:bye|goodbye|see you|see ya|take care|शुभरात्रि|फिर मिलेंगे|अलविदा|বিদায়|বিদায়|பிரியாவிடை|వీడ్కోలు|निरोप|આવજો|ವಿದಾಯ|വിട|ਅਲਵਿਦਾ|خدا حافظ|ବିଦାୟ|বিদায়)$/.test(
      q
    )
  ) {
    return "goodbye";
  }

  if (/^(?:ok|okay|alright|all right|sure|yes|no|great|fine|got it|ठीक|ठीक है|अच्छा|हाँ|नहीं|ঠিক আছে|சரி|సరే|ठीक आहे|બરાબર|ಸರಿ|ശരി|ਠੀਕ ਹੈ|ٹھیک ہے|ଠିକ ଅଛି|ঠিক আছে)$/.test(q)) {
    return "acknowledgement";
  }

  return null;
}

