// ---------------------------------------------------------------------------
// Multilingual content for catalogue-grounded chatbot explanations.
//
// Two content families live here, one per supported answer language:
//
//   PHRASES      — generic sentence templates (headers, what-a-value-means,
//                  next-steps, status sentences) shared by every test.
//   TEST_CONTENT — per-test "what this test is" definition and everyday
//                  lifestyle/diet tips.
//
// WHY A SEPARATE MODULE
// explain.ts holds the logic (test detection + composition); this module holds
// only strings, mirroring how translations.ts / mock-phrases.ts keep their
// phrasebooks out of the pipeline code.
//
// REVIEW STATUS (do not edit without reading this)
// English and Hindi are the originals, reviewed alongside src/lib/data.ts.
// The other twelve are new translations written for this feature and have NOT
// yet been through a native-speaker clinical review. REVIEWED_EXPLAIN_LANGS
// records which is which, and agent.ts attaches an
// `explain_language_unreviewed:<lang>` safety note when it serves the others,
// so a reviewer can find them.
// ---------------------------------------------------------------------------

